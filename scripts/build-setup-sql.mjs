// Concatenates supabase/migrations/*.sql + seed.sql into supabase/setup.sql —
// a single file you can paste into the Supabase SQL editor (no CLI needed).
// Run: npm run db:setup-sql   (tests/db/setup-sql.test.ts fails if it's stale)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = new URL("../supabase/", import.meta.url);

export function buildSetupSql() {
  const files = readdirSync(new URL("migrations/", dir)).filter((f) => f.endsWith(".sql")).sort();
  const parts = files.map((f) => `-- ===== migrations/${f} =====\n${readFileSync(new URL(`migrations/${f}`, dir), "utf8").trim()}\n`);
  parts.push(`-- ===== seed.sql =====\n${readFileSync(new URL("seed.sql", dir), "utf8").trim()}\n`);
  return [
    "-- TwinOS v2 — full database setup. GENERATED by scripts/build-setup-sql.mjs; do not edit by hand.",
    "-- Paste into Supabase → SQL Editor → Run, once, on a fresh project.",
    "",
    ...parts,
  ].join("\n");
}

if (import.meta.url === `file:///${process.argv[1]?.replace(/\\/g, "/").replace(/^\//, "")}`) {
  writeFileSync(new URL("setup.sql", dir), buildSetupSql());
  console.log("wrote supabase/setup.sql");
}
