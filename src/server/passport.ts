import "server-only";
import { createHash } from "node:crypto";
import type { SupabaseClient } from "@supabase/supabase-js";
import { createAdminClient } from "@/lib/supabase/admin";

/**
 * Twin Passport (F13, plan §15): export everything, delete everything.
 * Export runs AS the user (RLS-scoped), so it can only ever contain their own rows.
 */

export const AI_LABEL = "AI-generated by TwinOS — represents patterns from what you shared; not you, and it can be wrong.";

/** Tables and the columns to export. Embeddings / tsvectors are derived data, left out. */
const EXPORT_TABLES: Record<string, string> = {
  profiles: "*",
  consent_ledger: "*",
  memories: "id,content,summary,kind,source_type,source_ref,importance,context_qualifier,valid_from,valid_to,recorded_at,superseded_by,influence,category,memory_key,confidence,evidence,last_used_at,created_at",
  memory_revisions: "*",
  goals: "*",
  preferences: "*",
  training_answers: "*",
  decision_traits: "*",
  trait_snapshots: "*",
  chats: "*",
  messages: "*",
  message_feedback: "*",
  predictions: "*",
  feedback: "*",
  outcomes: "*",
  calibration_stats: "*",
  duel_rounds: "*",
  connector_accounts: "id,provider,scopes,status,created_at",
  action_proposals: "*",
  audit_logs: "*",
  usage_budget: "*",
};

export async function exportPassport(sb: SupabaseClient, userId: string) {
  const entries = await Promise.all(
    Object.entries(EXPORT_TABLES).map(async ([table, cols]) => {
      // Column lists are built at runtime, so declare the row shape instead of letting
      // supabase-js try to infer it from the string.
      const { data, error } = await sb.from(table).select(cols).returns<Record<string, unknown>[]>();
      if (error) throw new Error(`export ${table}: ${error.message}`);
      return [table, data] as const;
    }),
  );
  const data: Record<string, Record<string, unknown>[]> = Object.fromEntries(entries);
  // Label model-generated content (EU AI Act Art. 50) wherever it appears.
  data.predictions = (data.predictions ?? []).map((p) => ({ ...p, _label: AI_LABEL }));

  await sb.from("consent_ledger").insert({ user_id: userId, event: "export", scope: "all", detail: { tables: Object.keys(EXPORT_TABLES).length } });
  return {
    format: "twinos-passport@1",
    exportedAt: new Date().toISOString(),
    notice: AI_LABEL,
    data,
  };
}

/**
 * Verified delete-all: counts rows, writes a receipt with NO personal content (hashed id),
 * then deletes the auth user — every user table cascades from auth.users.
 */
export async function deleteEverything(sb: SupabaseClient, userId: string): Promise<{ rowsDeleted: Record<string, number> }> {
  const counts = await Promise.all(
    Object.keys(EXPORT_TABLES).map(async (t) => {
      const { count } = await sb.from(t).select("*", { count: "exact", head: true });
      return [t, count ?? 0] as const;
    }),
  );
  const rowsDeleted = Object.fromEntries(counts);

  const admin = createAdminClient();
  const { error: logErr } = await admin.from("deletion_log").insert({
    user_id_hash: createHash("sha256").update(userId).digest("hex"),
    rows_deleted: rowsDeleted,
  });
  if (logErr) throw logErr;
  const { error } = await admin.auth.admin.deleteUser(userId);
  if (error) throw error;

  // Verify: nothing of theirs remains.
  const { count } = await admin.from("memories").select("id", { count: "exact", head: true }).eq("user_id", userId);
  if (count) throw new Error("Deletion could not be verified");
  return { rowsDeleted };
}
